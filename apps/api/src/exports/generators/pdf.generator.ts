import { ExportGenerationMetadata } from '@shipde/contracts';

/**
 * Escapes characters for PDF literal text strings in content streams.
 */
function escapePdfText(str: unknown): string {
  if (str === null || str === undefined) return '';
  return (
    String(str)
      .replace(/\\/g, '\\\\')
      .replace(/\(/g, '\\(')
      .replace(/\)/g, '\\)')
      // Strip or replace non-ASCII characters to standard ASCII for base Type1 fonts
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '')
  );
}

/**
 * Generates a valid conformant PDF 1.4 document buffer with exact xref offsets.
 */
export function generatePdf(
  metadata: ExportGenerationMetadata,
  headers: { key: string; label: string }[],
  rows: Record<string, unknown>[]
): Buffer {
  const contentStreamCommands: string[] = [];

  // Header Box
  contentStreamCommands.push('0.9 0.95 1 rg 30 750 535 60 re f'); // Light blue background
  contentStreamCommands.push('0.2 0.3 0.5 RG 1 w 30 750 535 60 re S'); // Border

  // Title
  contentStreamCommands.push(
    'BT /F2 16 Tf 0.1 0.2 0.4 rg 45 785 Td (SHIP DE - EXPORT REPORT) Tj ET'
  );

  // Metadata Subtitle
  contentStreamCommands.push(
    `BT /F1 9 Tf 0.3 0.3 0.3 rg 45 765 Td (Resource: ${escapePdfText(
      metadata.resource
    )} | Format: ${metadata.format.toUpperCase()} | Generated: ${escapePdfText(
      metadata.generated_at
    )}) Tj ET`
  );

  // Metadata Details Table
  contentStreamCommands.push('0.96 0.96 0.96 rg 30 670 535 70 re f');
  contentStreamCommands.push('0.8 0.8 0.8 RG 0.5 w 30 670 535 70 re S');

  const metaRows = [
    `Export ID: ${metadata.export_id}`,
    `Tenant ID: ${metadata.merchant_id}`,
    `Requested By: ${metadata.requested_by} (${metadata.user_role})`,
    `Rule Version: ${metadata.rule_version} | Records: ${metadata.total_rows} (Succeeded: ${metadata.succeeded_rows}, Failed: ${metadata.failed_rows})`,
    `Checksum (SHA-256): ${metadata.checksum_sha256}`,
  ];

  let metaY = 725;
  for (const item of metaRows) {
    contentStreamCommands.push(
      `BT /F1 8 Tf 0.2 0.2 0.2 rg 40 ${metaY} Td (${escapePdfText(item)}) Tj ET`
    );
    metaY -= 11;
  }

  // Data Table
  const tableTopY = 645;
  const colWidth = Math.floor(535 / Math.max(1, headers.length));

  // Table Header row background & border
  contentStreamCommands.push(`0.85 0.9 0.95 rg 30 ${tableTopY - 15} 535 18 re f`);
  contentStreamCommands.push(`0.6 0.7 0.8 RG 1 w 30 ${tableTopY - 15} 535 18 re S`);

  // Column headers
  for (let c = 0; c < headers.length; c++) {
    const colX = 35 + c * colWidth;
    const headerTitle = headers[c].label;
    contentStreamCommands.push(
      `BT /F2 9 Tf 0.1 0.2 0.3 rg ${colX} ${tableTopY - 11} Td (${escapePdfText(
        headerTitle
      )}) Tj ET`
    );
  }

  // Data rows (render up to available page height, e.g. 35 rows)
  let rowY = tableTopY - 30;
  const maxRowsOnPage = Math.min(rows.length, 35);

  for (let r = 0; r < maxRowsOnPage; r++) {
    const row = rows[r];
    // Alternating row background
    if (r % 2 === 1) {
      contentStreamCommands.push(`0.98 0.98 0.98 rg 30 ${rowY - 4} 535 14 re f`);
    }
    contentStreamCommands.push(`0.9 0.9 0.9 RG 0.5 w 30 ${rowY - 4} 535 14 re S`);

    for (let c = 0; c < headers.length; c++) {
      const colX = 35 + c * colWidth;
      const val = row[headers[c].key];
      const strVal = String(val === null || val === undefined ? '' : val);
      // Truncate cell text if too long for column
      const cellText = strVal.length > 25 ? `${strVal.substring(0, 22)}...` : strVal;
      contentStreamCommands.push(
        `BT /F1 8 Tf 0.2 0.2 0.2 rg ${colX} ${rowY} Td (${escapePdfText(cellText)}) Tj ET`
      );
    }
    rowY -= 15;
  }

  // Truncation note if rows exceed page
  if (rows.length > maxRowsOnPage) {
    contentStreamCommands.push(
      `BT /F1 8 Tf 0.5 0.5 0.5 rg 40 ${rowY} Td (... and ${
        rows.length - maxRowsOnPage
      } more records omitted for PDF page summary) Tj ET`
    );
  }

  // Page Footer
  contentStreamCommands.push('0.7 0.7 0.7 RG 0.5 w 30 40 535 0.5 re S');
  contentStreamCommands.push(
    `BT /F1 8 Tf 0.4 0.4 0.4 rg 35 28 Td (Generated by Ship De Export Engine - SHA256: ${metadata.checksum_sha256.substring(
      0,
      16
    )}...) Tj ET`
  );

  const streamBody = contentStreamCommands.join('\n');
  const streamLength = Buffer.byteLength(streamBody, 'utf-8');

  // Build PDF Objects
  const parts: string[] = [];
  const byteOffsets: number[] = [];

  parts.push('%PDF-1.4\n%\xE2\xE3\xCF\xD3\n');

  function addObject(objNum: number, content: string) {
    // Current byte offset in parts
    const currentOffset = Buffer.byteLength(parts.join(''), 'utf-8');
    byteOffsets[objNum] = currentOffset;
    parts.push(`${objNum} 0 obj\n${content}\nendobj\n`);
  }

  // 1: Catalog
  addObject(1, '<< /Type /Catalog /Pages 2 0 R >>');

  // 2: Pages
  addObject(2, '<< /Type /Pages /Kids [3 0 R] /Count 1 >>');

  // 3: Page (A4: 595.28 x 841.89)
  addObject(
    3,
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595.28 841.89] /Contents 4 0 R /Resources << /Font << /F1 5 0 R /F2 6 0 R >> >> >>'
  );

  // 4: Contents stream
  addObject(4, `<< /Length ${streamLength} >>\nstream\n${streamBody}\nendstream`);

  // 5: Font F1 (Helvetica)
  addObject(5, '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>');

  // 6: Font F2 (Helvetica-Bold)
  addObject(6, '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>');

  // Cross-reference table
  const startXref = Buffer.byteLength(parts.join(''), 'utf-8');
  parts.push('xref\n0 7\n0000000000 65535 f \n');
  for (let i = 1; i <= 6; i++) {
    const offsetStr = String(byteOffsets[i]).padStart(10, '0');
    parts.push(`${offsetStr} 00000 n \n`);
  }

  // Trailer
  parts.push(`trailer\n<< /Size 7 /Root 1 0 R >>\nstartxref\n${startXref}\n%%EOF\n`);

  return Buffer.from(parts.join(''), 'utf-8');
}
